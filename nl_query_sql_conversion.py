def generate_sql(schema, instruction, query):
    query = query.lower().strip()
    context = vector_search(query, top_k=3)
    print("context is   ", context)

    prompt = f"""
    Database Schema:
    {schema}

    General Instruction:
    {instruction}

    Relevant Context:
    {context}
    #{docs}

    User Query:
    {query}

    SQL query:

    """

    inputs = tokenizer(prompt, return_tensors="pt")

    # Generate only continuation (skip prompt echo)
    outputs = model.generate(
        **inputs,
        max_new_tokens=128,
        return_dict_in_generate=True
    )

    # Decode only the new tokens after the prompt
    raw_sql = tokenizer.decode(
        outputs.sequences[0][inputs["input_ids"].shape[-1]:],
        skip_special_tokens=True
    ).strip()

    # --- Extraction: keep everything from SELECT until ; ---
    match = re.search(r"(SELECT.*?;)", raw_sql, re.DOTALL | re.IGNORECASE)
    if match:
        sql_query = match.group(1).strip()
    else:
        sql_query = raw_sql

    # --- Post-processing fixers ---
    def fix_sql_parentheses(sql: str) -> str:
        if "AND" in sql and "OR" in sql:
            sql = re.sub(r"AND (.+) OR (.+)", r"AND (\1 OR \2)", sql)
        return sql

    def fix_sql_semicolon(sql: str) -> str:
        sql = re.sub(r";\)", ")", sql)   # fix misplaced semicolon inside parentheses
        sql = sql.rstrip()
        if not sql.endswith(";"):
            sql += ";"
        return sql

    sql_query = fix_sql_parentheses(sql_query)
    sql_query = fix_sql_semicolon(sql_query)

    print("Natural language query:", query)


    return sql_query

import re

def normalize_sql(sql_query: str) -> str:
    # Regex to catch aggregate functions with optional spaces
    sql_query = re.sub(r"\bsum\s*\(", "SUM(", sql_query, flags=re.IGNORECASE)
    sql_query = re.sub(r"\bcount\s*\(", "COUNT(", sql_query, flags=re.IGNORECASE)
    sql_query = re.sub(r"\bmax\s*\(", "MAX(", sql_query, flags=re.IGNORECASE)
    sql_query = re.sub(r"\bmin\s*\(", "MIN(", sql_query, flags=re.IGNORECASE)
    sql_query = re.sub(r"\bavg\s*\(", "AVG(", sql_query, flags=re.IGNORECASE)
    return sql_query

import re

def clean_sql(nl_query: str, sql_query: str) -> str:
    q = nl_query.lower()

    # ✅ Team mapping
    team_map = {
        "team1": "Kolkata Knight Riders",
        "team 1": "Kolkata Knight Riders",
        "kkr": "Kolkata Knight Riders",
        "team2": "Royal Challengers Bangalore",
        "team 2": "Royal Challengers Bangalore",
        "rcb": "Royal Challengers Bangalore"
    }
    for key, value in team_map.items():
        sql_query = re.sub(rf"(['\"]?{key}['\"]?)", f"'{value}'", sql_query, flags=re.IGNORECASE)

    # ✅ Handle innings filters safely
    if "first innings" in q or "innings 1" in q:
        sql_query = re.sub(r"where\s+innings\s*=\s*['\"]?\d+['\"]?", "WHERE innings = 1", sql_query, flags=re.IGNORECASE)
    elif "second innings" in q or "innings 2" in q:
        sql_query = re.sub(r"where\s+innings\s*=\s*['\"]?\d+['\"]?", "WHERE innings = 2", sql_query, flags=re.IGNORECASE)
    # ❌ Removed the else block — don’t strip WHERE innings blindly

    # ✅ Normalize whitespace
    sql_query = re.sub(r'\s+', ' ', sql_query)

    # ✅ Standardize keyword casing
    for kw in ["select", "from", "where", "group by", "order by", "limit"]:
        sql_query = re.sub(rf"\b{kw}\b", kw.upper(), sql_query, flags=re.IGNORECASE)

    # ✅ Remove markdown fences if present
    sql_query = re.sub(r"```sql", "", sql_query, flags=re.IGNORECASE)
    sql_query = re.sub(r"```", "", sql_query)

    return sql_query.strip()

